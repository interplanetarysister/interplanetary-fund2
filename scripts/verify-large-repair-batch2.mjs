const worker=read("worker/index.js");
const wrangler=read("wrangler.jsonc");
const bell=read("src/components/NotificationBell.jsx");
const help=read("src/pages/Help.jsx");
const social=read("src/pages/Social.jsx");
const giving=read("src/pages/MyGiving.jsx");
const discover=read("src/pages/Discover.jsx");
const institutions=read("src/pages/Institutions.jsx");
const withdrawals=read("src/pages/Withdrawals.jsx");
const gpay=read("src/components/payments/GooglePayButton.jsx");
const external=read("src/pages/ExternalAccounts.jsx");
const del=read("base44/functions/deleteAccount/entry.ts");
must(worker.length>500 && wrangler.includes("main"),"Cloudflare runtime boundary missing");
for(const [name,src] of [["NotificationBell",bell],["Help",help],["Social",social],["MyGiving",giving],["Discover",discover],["Institutions",institutions],["ExternalAccounts",external]]) must(src.length>1000, name+" repair missing");
