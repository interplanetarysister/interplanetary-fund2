import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
const read=(p)=>readFileSync(new URL("../"+p, import.meta.url), "utf8");
const page = read("src/pages/MyGiving.jsx");
const backend = read("base44/functions/getMyGiving/entry.ts");
const row = read("src/components/giving/DonationRow.jsx");
const receipt = read("src/lib/receipt.js");
assert.match(page, /Array\.isArray\(data\.donations\)/, "reject malformed history");
assert.match(page, /role="group" aria-label="Giving environment"/, "live and sandbox distinguished");
assert.match(page, /to="\/discover"/, "Discover empty-state action present");
assert.match(page, /FlaskConical/, "sandbox icon");
assert.match(page, /HeartHandshake/, "giving icon");
assert.match(page, /ReceiptText/, "history icon");
assert.match(page, /status === "completed"/, "only completed records affect totals");
assert.match(page, /role="status"/, "accessible status");
assert.doesNotMatch(page, /setError\(.*?\.message/, "untrusted error details must not be displayed");
assert.match(backend, /donor_user_id: user\.id/, "server scopes history to the authenticated donor");
assert.match(backend, /FinancialOperation\.get/, "canonical ledger verified");
assert.match(backend, /operation\.state !== 'applied'/, "pending operations excluded from confirmed totals");
assert.match(backend, /capturedIds\.has/, "provider capture deduplication");
assert.match(backend, /recurring_supported: false/, "no fake recurring payments");
assert.match(row, /refunded/);
assert.match(row, /reversed/);
assert.match(row, /pending/);
assert.match(receipt, /SANDBOX TEST RECORD/);
assert.match(receipt, /Not a donation or tax receipt/);
console.log("My Giving owner scope, statuses, accessibility, icon and sandbox receipt contracts verified.");
